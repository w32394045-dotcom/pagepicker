#!/usr/bin/env node
/* PagePicker build: inlines CSS, core JS, locales and app JS into
   - index.html  (the single-file app, served by GitHub Pages and opened locally)
   - worker.js   (the same page inlined into a Cloudflare Worker)
   Run: node tools/build.mjs [--allow-missing]
   --allow-missing keeps going when a locale file is not translated yet (development only). */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(join(root, p), "utf8");
const write = (p, s) => writeFileSync(join(root, p), s, "utf8");
const allowMissing = process.argv.includes("--allow-missing");

const LANGS = ["zh-CN", "zh-TW", "ja", "ko", "fr", "de", "en"];

const dict = {};
const missing = [];
for (const lang of LANGS) {
  const file = `src/i18n/${lang}.json`;
  if (!existsSync(join(root, file))) {
    missing.push(lang);
    continue;
  }
  dict[lang] = JSON.parse(read(file));
}
if (missing.includes("en")) {
  console.error("fatal: src/i18n/en.json is required");
  process.exit(1);
}
if (missing.length) {
  const msg = `missing locales: ${missing.join(", ")}`;
  if (!allowMissing) {
    console.error(`fatal: ${msg}`);
    process.exit(1);
  }
  console.warn(`warning: ${msg} — building anyway`);
}

const css = read("src/styles.css");
const core = read("src/core.js");
const app = read("src/app.js");
const i18n = "var I18N = " + JSON.stringify(dict) + ";";

let html = read("src/index.template.html");
if ((html.match(/@@[A-Z]+@@/g) || []).length === 0) {
  console.error("fatal: index.template.html has no placeholders");
  process.exit(1);
}
html = html
  .replace("@@STYLES@@", () => css)
  .replace("@@CORE@@", () => core)
  .replace("@@I18N@@", () => i18n)
  .replace("@@APP@@", () => app);

const leftovers = html.match(/@@[A-Z]+@@/g);
if (leftovers) {
  console.error(`fatal: unreplaced placeholders: ${leftovers.join(", ")}`);
  process.exit(1);
}
if (/<\/script>/i.test(core + app + i18n)) {
  console.error("fatal: script sources must not contain </script>");
  process.exit(1);
}

write("index.html", html);

/* One request, one file: the Worker serves exactly the same bytes as index.html. */
const worker = [
  "/* PagePicker — Cloudflare Worker. Generated by tools/build.mjs; do not edit by hand. */",
  "/* The whole app is inlined so a single request gets everything and nothing else is fetched. */",
  "",
  "const HTML = " + JSON.stringify(html) + ";",
  "",
  "const COMMON = {",
  '  "x-content-type-options": "nosniff",',
  '  "referrer-policy": "no-referrer",',
  '  "x-frame-options": "SAMEORIGIN"',
  "};",
  "",
  "export default {",
  "  async fetch(request) {",
  "    const url = new URL(request.url);",
  '    if (url.pathname === "/" || url.pathname === "/index.html") {',
  "      return new Response(request.method === \"HEAD\" ? null : HTML, {",
  '        headers: { ...COMMON, "content-type": "text/html; charset=utf-8", "cache-control": "public, max-age=300" }',
  "      });",
  "    }",
  '    if (url.pathname === "/robots.txt") {',
  '      return new Response("User-agent: *\\nAllow: /\\n", {',
  '        headers: { ...COMMON, "content-type": "text/plain; charset=utf-8" }',
  "      });",
  "    }",
  '    return new Response("Not found", { status: 404, headers: { ...COMMON, "content-type": "text/plain; charset=utf-8" } });',
  "  }",
  "};",
  ""
].join("\n");
write("worker.js", worker);

const kb = (s) => (s.length / 1024).toFixed(1) + " KB";
console.log(`index.html  ${kb(html)}`);
console.log(`worker.js   ${kb(worker)}`);
console.log(`locales     ${Object.keys(dict).join(", ")}${missing.length ? " (missing: " + missing.join(", ") + ")" : ""}`);
